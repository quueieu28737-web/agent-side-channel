# Recompute deterministic O8 scripts while capturing writes in memory. This checker
# compares generated bytes and does not silently overwrite a differing source result.
def exact_recompute(script, expected_names):
    captured={}
    def capture(path, data, encoding=None, errors=None, newline=None):
        path=path.resolve()
        assert path.parent==O.resolve() and path.name in expected_names, ('Unexpected write',path)
        buffer=io.BytesIO()
        stream=io.TextIOWrapper(buffer,encoding=encoding or 'utf-8',errors=errors or 'strict',newline=newline)
        stream.write(data);stream.flush()
        captured[path.name]=buffer.getvalue()
        return len(data)
    with patch.object(Path,'write_text',capture), redirect_stdout(io.StringIO()):
        runpy.run_path(str(O/script),run_name='__main__')
    assert set(captured)==set(expected_names)
    assert all((O/n).read_bytes()==v for n,v in captured.items()), ('Recomputed O8 result differs',script)
    return {n:hashlib.sha256(v).hexdigest() for n,v in captured.items()}

